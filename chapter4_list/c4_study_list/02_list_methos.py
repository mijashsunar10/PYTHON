#List methods
#There are several methods in lists
friends = ["anmol", "mijash", 0 , 2, True, "hello", 3.4 ]

friends.append("new friend")  # Adds a new element to the end of the list
print(friends)

l1=[1,3,5,2,4]
l1.sort()
print(l1)  # Sorts the list in ascending order

l1.reverse()
print(l1)  # Reverses the order of the list

l1.insert(2,10)  # Inserts 10 at index 2
print(l1)  

l1.remove(5)
print(l1)  # Removes the first occurrence of 0 from the list 