s1 = {1, 2, 3, 4}
s2 = {3, 4, 5, 6}
s3 = s1.union(s2)  # Union of two sets
print(s3)

s4 = s1|s2
print(s4)  # Union using the | operator

s5 = s1.intersection(s2)  # Intersection of two sets
print(s5)                                                       

s6 = s1 & s2  # Intersection using the & operator
print(s6)